package report

import (
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/luminariadev/raksa-siem/internal/schema"
)

var reAttackTechnique = regexp.MustCompile(`\bT\d{4}(?:\.\d{3})?\b`)

type navTechnique struct {
	TechniqueID string `json:"techniqueID"`
	Score       int    `json:"score"`
	Color       string `json:"color"`
	Comment     string `json:"comment"`
	Enabled     bool   `json:"enabled"`
}

// FormatAttackNavRender exports a MITRE ATT&CK Navigator v4.5 layer JSON highlighting observed techniques.
func FormatAttackNavRender(rep schema.Report) (string, error) {
	type techAgg struct {
		score int
		sev   schema.Severity
		rules map[string]bool
	}
	found := make(map[string]*techAgg)

	recordTech := func(techID string, f schema.Finding) {
		techID = strings.ToUpper(strings.TrimSpace(techID))
		if techID == "" {
			return
		}
		sc := attackScoreForSeverity(f.Severity)
		agg, ok := found[techID]
		if !ok {
			agg = &techAgg{score: sc, sev: f.Severity, rules: make(map[string]bool)}
			found[techID] = agg
		} else if sc > agg.score {
			agg.score = sc
			agg.sev = f.Severity
		}
		agg.rules[f.RuleID] = true
	}

	for _, f := range rep.Findings {
		var matched []string
		if meta, ok := schema.LookupRule(f.RuleID); ok {
			matched = append(matched, reAttackTechnique.FindAllString(strings.ToUpper(meta.Standard), -1)...)
		}
		if f.Evidence != nil {
			if mt, ok := f.Evidence["mitre_technique"]; ok && mt != nil {
				matched = append(matched, reAttackTechnique.FindAllString(strings.ToUpper(fmt.Sprint(mt)), -1)...)
			}
			if tags, ok := f.Evidence["tags"]; ok && tags != nil {
				matched = append(matched, reAttackTechnique.FindAllString(strings.ToUpper(fmt.Sprint(tags)), -1)...)
			}
		}
		for _, tid := range matched {
			recordTech(tid, f)
		}
	}

	var techniques []navTechnique
	var keys []string
	for k := range found {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		agg := found[k]
		var rList []string
		for r := range agg.rules {
			rList = append(rList, r)
		}
		sort.Strings(rList)
		techniques = append(techniques, navTechnique{
			TechniqueID: k,
			Score:       agg.score,
			Color:       attackColorForSeverity(agg.sev),
			Comment:     "raksa-siem rules: " + strings.Join(rList, ", "),
			Enabled:     true,
		})
	}
	if techniques == nil {
		techniques = []navTechnique{}
	}

	layer := map[string]any{
		"name":   "Raksa SIEM Detections",
		"domain": "enterprise-attack",
		"versions": map[string]string{
			"attack":    "15",
			"navigator": "4.9.5",
			"layer":     "4.5",
		},
		"description": fmt.Sprintf("Generated by raksa-siem v%s (%d findings)", schema.Version, len(rep.Findings)),
		"gradient": map[string]any{
			"colors":   []string{"#3b82f6", "#eab308", "#ef4444"},
			"minValue": 0,
			"maxValue": 100,
		},
		"techniques": techniques,
	}
	raw, err := json.MarshalIndent(layer, "", "  ")
	if err != nil {
		return "", err
	}
	return string(raw) + "\n", nil
}

func attackScoreForSeverity(sev schema.Severity) int {
	switch sev {
	case schema.SeverityCritical:
		return 100
	case schema.SeverityHigh:
		return 75
	case schema.SeverityMedium:
		return 50
	case schema.SeverityLow:
		return 25
	default:
		return 10
	}
}

func attackColorForSeverity(sev schema.Severity) string {
	switch sev {
	case schema.SeverityCritical:
		return "#dc2626"
	case schema.SeverityHigh:
		return "#ea580c"
	case schema.SeverityMedium:
		return "#d97706"
	default:
		return "#2563eb"
	}
}
